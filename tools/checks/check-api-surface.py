# --- the header lists ----------------------------------------------------------


def cmake_list(text: str, name: str) -> list[str]:
    """The entries of `set(NAME ...)` in a CMake file, comments dropped."""
    text = "\n".join(line.split("#", 1)[0] for line in text.splitlines())
    m = re.search(r"set\(\s*" + re.escape(name) + r"\s+([^)]*)\)", text)
    if not m:
        raise SurfaceError(f"no set({name} ...)")
    return m.group(1).split()


def module_files(repo: Path, keyword: str, suffix: str) -> list[str]:
    """The model/ and helper/ files of build_lib's KEYWORD section in CMakeLists.txt."""
    text = (repo / "CMakeLists.txt").read_text()
    m = re.search(keyword + r"\s+(.*?)(?=\n\s*[A-Z_]{4,}\s|\))", text, re.S)
    if not m:
        raise SurfaceError(f"CMakeLists.txt: no {keyword}")
    return [
        f for f in m.group(1).split() if f.startswith(("model/", "helper/")) and f.endswith(suffix)
    ]


def core_headers(repo: Path) -> list[str]:
    text = (repo / "core" / "swarm-core-sources.cmake").read_text()
    return cmake_list(text, "SWARM_CORE_HEADERS") + cmake_list(text, "SWARM_CORE_TESTBENCH_HEADERS")


# --- clang's JSON AST, streamed -------------------------------------------------


def clang_binary() -> str:
    clang = os.environ.get("CLANG") or shutil.which("clang++-18") or ""
    if not clang:
        raise SurfaceError("clang++-18 not found (set CLANG to override)")
    return clang


FILE_LINE = re.compile(r'^\s*"file": "(.*)",?$')


def top_level_namespaces(cmd: list[str], cwd: Path, wanted: set[str]):
    """Yield (file, node) for each top-level NamespaceDecl named in WANTED.

    The JSON dump of a translation unit with the standard library and ns-3 is
    about a gigabyte, so it is read line by line: clang pretty-prints it, each
    top-level declaration starts at `    {` and ends at `    }`, and a location
    names its file only when it differs from the previous one printed, so the
    file of a declaration is the last `"file"` line seen before it (an
    `includedFrom` file does not count). Only the namespaces asked for are
    parsed."""
    proc = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    current = ""
    chunk: list[str] | None = None
    chunk_file = ""
    in_loc = False
    previous = ""
    for line in proc.stdout:
        if '"file"' in line and previous.strip() != '"includedFrom": {':
            m = FILE_LINE.match(line)
            if m:
                current = json.loads('"' + m.group(1) + '"')
                if in_loc:
                    chunk_file = current
        if chunk is not None:
            chunk.append(line)
            if line.startswith('      "range"'):
                in_loc = False
            if line.rstrip().rstrip(",") == "    }":
                node = json.loads("".join(chunk).rstrip().rstrip(","))
                if node.get("kind") == "NamespaceDecl" and node.get("name") in wanted:
                    yield chunk_file, node
                chunk = None
                in_loc = False
        elif line.rstrip() == "    {":
            # The declaration's file is the current one unless its own loc names another.
            chunk, chunk_file, in_loc = [line], current, True
        previous = line
    err = proc.stderr.read()
    if proc.wait() != 0:
        raise SurfaceError("clang failed:\n" + err[-4000:])


# --- rendering ------------------------------------------------------------------


def expr(node: dict) -> str:
    """A compact, deterministic rendering of an initialiser or default argument."""
    kind = node.get("kind", "")
    inner = node.get("inner", [])
    if kind == "CXXBoolLiteralExpr":
        return "true" if node.get("value") else "false"
    if "value" in node and kind in (
        "ConstantExpr",
        "IntegerLiteral",
        "FloatingLiteral",
        "CharacterLiteral",
        "StringLiteral",
        "CXXBoolLiteralExpr",
        "FixedPointLiteral",
    ):
        return str(node["value"])
    if kind == "CXXNullPtrLiteralExpr":
        return "nullptr"
    if kind == "DeclRefExpr":
        ref = node.get("referencedDecl", {})
        return ref.get("name", "?")
    if kind in ("UnaryOperator",):
        return node.get("opcode", "?") + "".join(expr(c) for c in inner)
    if kind in ("BinaryOperator", "CompoundAssignOperator"):
        return f" {node.get('opcode', '?')} ".join(expr(c) for c in inner)
    if kind == "MemberExpr":
        return "".join(expr(c) for c in inner) + "." + node.get("name", "?")
    if kind in ("CallExpr", "CXXMemberCallExpr", "CXXOperatorCallExpr"):
        parts = [expr(c) for c in inner]
        return (parts[0] if parts else "?") + "(" + ", ".join(parts[1:]) + ")"
    if kind in ("CXXTemporaryObjectExpr", "CXXFunctionalCastExpr"):
        # written by the author: Type{...} / Type(...)
        return node.get("type", {}).get("qualType", "") + "{" + ", ".join(leaves(node)) + "}"
    if kind in ("CXXConstructExpr", "InitListExpr"):
        # braces the standard library nests differently (std::array's inner
        # aggregate): flattened to the values, so the line does not depend on it
        return "{" + ", ".join(leaves(node)) + "}"
    if kind == "CXXDefaultArgExpr":
        return "default"
    # Casts, parentheses, materialisations: their operand says it.
    if inner:
        return ", ".join(expr(c) for c in inner)
    return kind


def leaves(node: dict) -> list[str]:
    out = []
    for c in node.get("inner", []):
        k = c.get("kind")
        if k in ("CXXConstructExpr", "InitListExpr") or (
            k
            in (
                "ImplicitCastExpr",
                "MaterializeTemporaryExpr",
                "CXXBindTemporaryExpr",
                "ExprWithCleanups",
            )
            and len(c.get("inner", [])) == 1
            and c["inner"][0].get("kind") in ("CXXConstructExpr", "InitListExpr")
        ):
            out += leaves(c if k in ("CXXConstructExpr", "InitListExpr") else c["inner"][0])
        elif k != "ImplicitValueInitExpr":
            out.append(expr(c))
    return out


def template_prefix(params: list[dict]) -> str:
    out = []
    for p in params:
        if p["kind"] == "TemplateTypeParmDecl":
            s = f"{p.get('tagUsed', 'typename')} {p.get('name', '')}".rstrip()
            if p.get("isParameterPack"):
                s += "..."
        elif p["kind"] == "NonTypeTemplateParmDecl":
            s = f"{p.get('type', {}).get('qualType', '?')} {p.get('name', '')}".rstrip()
        else:
            s = p["kind"]
        default = [c for c in p.get("inner", []) if c.get("kind") == "TemplateArgument"]
        if default:
            d = default[0]
            s += " = " + (
                d["type"]["qualType"]
                if "type" in d
                else ", ".join(expr(c) for c in d.get("inner", []))
            )
        out.append(s)
    return "template<" + ", ".join(out) + "> "


def specifiers(node: dict, src: bytes) -> str:
    """The source between a declaration's start and its name (where `explicit` is,
    which clang's JSON does not report)."""
    begin = node.get("range", {}).get("begin", {}).get("offset")
    name = node.get("loc", {}).get("offset")
    if begin is None or name is None or not src:
        return ""
    return src[begin:name].decode(errors="replace")


def function_line(area: str, qname: str, node: dict, access: str, tmpl: str, src: bytes) -> str:
    flags = [access] if access else []
    for key, word in (("virtual", "virtual"), ("constexpr", "constexpr")):
        if node.get(key):
            flags.append(word)
    if re.search(r"\bexplicit\b", specifiers(node, src)):
        flags.append("explicit")
    if node.get("storageClass") == "static":
        flags.append("static")
    sig = node.get("type", {}).get("qualType", "?")
    if node.get("pure"):
        sig += " = 0"
    if node.get("explicitlyDeleted"):
        sig += " = delete"
    if node.get("explicitlyDefaulted") == "default":
        sig += " = default"
    defaults = []
    params = [c for c in node.get("inner", []) if c.get("kind") == "ParmVarDecl"]
    for i, p in enumerate(params):
        if "init" in p and p.get("inner"):
            defaults.append(f"{i}={expr(p['inner'][0])}")
    if defaults:
        sig += " [defaults " + "; ".join(defaults) + "]"
    head = f"{area} {tmpl}function {qname}"
    return f"{head} {' '.join(flags)}: {sig}" if flags else f"{head}: {sig}"


TEMPLATE_PARAMS = {"TemplateTypeParmDecl", "NonTypeTemplateParmDecl", "TemplateTemplateParmDecl"}


def walk(
    area: str,
    scope: str,
    nodes: list[dict],
    default_access: str,
    out: set[str],
    src: bytes,
    tmpl: str = "",
) -> None:
    access = default_access
    for node in nodes:
        kind = node.get("kind")
        if kind == "AccessSpecDecl":
            access = node["access"]
            continue
        if node.get("isImplicit") or "previousDecl" in node and kind in FUNCTION_KINDS:
            continue
        if access == "private":
            continue
        if any(c.get("kind") == "DeprecatedAttr" for c in node.get("inner", [])) and node.get(
            "name"
        ):
            # its own line: deprecating is a minor change, so the item's line stays as it was
            out.add(f"{area} deprecated {scope}::{node['name']}")
        shown = access if default_access else ""
        name = node.get("name", "")
        qname = f"{scope}::{name}" if name else scope
        if kind == "NamespaceDecl":
            if name not in SKIP_NAMESPACES:
                walk(area, qname, node.get("inner", []), "", out, src)
        elif kind == "CXXRecordDecl":
            if not node.get("completeDefinition") or not name:
                continue
            tag = node.get("tagUsed", "class")
            bases = [
                f"{b.get('access', 'public')} {b['type']['qualType']}"
                for b in node.get("bases", [])
                if b.get("access", "public") != "private"
            ]
            line = f"{area} {tmpl}{tag} {qname}"
            if shown:
                line += f" ({shown})"
            if bases:
                line += " : " + ", ".join(bases)
            out.add(line)
            walk(
                area,
                qname,
                node.get("inner", []),
                "private" if tag == "class" else "public",
                out,
                src,
            )
        elif kind in ("ClassTemplateDecl", "FunctionTemplateDecl", "TypeAliasTemplateDecl"):
            params = [c for c in node.get("inner", []) if c["kind"] in TEMPLATE_PARAMS]
            rest = [c for c in node.get("inner", []) if c["kind"] not in TEMPLATE_PARAMS]
            rest = [c for c in rest if c["kind"] not in ("ClassTemplateSpecializationDecl",)]
            if kind == "FunctionTemplateDecl":
                rest = rest[:1]  # the pattern; the rest are implicit instantiations
            inner = [{"kind": "AccessSpecDecl", "access": access}] if default_access else []
            walk(area, scope, inner + rest, default_access, out, src, template_prefix(params))
        elif kind in FUNCTION_KINDS:
            out.add(function_line(area, qname, node, shown, tmpl, src))
        elif kind == "FieldDecl":
            line = f"{area} field {qname}"
            line += f" ({shown})" if shown else ""
            line += f": {node['type']['qualType']}"
            if node.get("inner") and node.get("hasInClassInitializer"):
                line += " = " + expr(node["inner"][0])
            out.add(line)
        elif kind == "VarDecl":
            flags = [shown] if shown else []
            if node.get("constexpr"):
                flags.append("constexpr")
            if node.get("storageClass") == "static":
                flags.append("static")
            line = f"{area} {tmpl}var {qname}"
            line += f" ({' '.join(flags)})" if flags else ""
            line += f": {node['type']['qualType']}"
            if "init" in node and node.get("inner"):
                line += " = " + expr(node["inner"][0])
            out.add(line)
        elif kind == "EnumDecl":
            scoped = node.get("scopedEnumTag", "")
            under = node.get("fixedUnderlyingType", {}).get("qualType", "")
            line = f"{area} enum{' ' + scoped if scoped else ''} {qname}"
            line += f" ({shown})" if shown else ""
            line += f" : {under}" if under else ""
            out.add(line)
            value = -1
            for c in node.get("inner", []):
                if c.get("kind") != "EnumConstantDecl":
                    continue
                consts = [x for x in c.get("inner", []) if x.get("kind") == "ConstantExpr"]
                value = int(consts[0]["value"]) if consts else value + 1
                enum_scope = qname if scoped or not name else scope
                out.add(f"{area} enumerator {enum_scope}::{c['name']} = {value}")
        elif kind in ("TypedefDecl", "TypeAliasDecl"):
            line = f"{area} {tmpl}alias {qname}"
            line += f" ({shown})" if shown else ""
            out.add(line + f" = {node['type']['qualType']}")
        # using-declarations, friends, static_asserts: not names a consumer calls


def source(work: Path, f: str) -> bytes:
    try:
        return (work / f).read_bytes()
    except OSError:
        return b""


def cxx_surface(repo: Path, include: Path | None, work: Path) -> set[str]:
    clang = clang_binary()
    out: set[str] = set()
    base = [clang, "-x", "c++", "-std=c++23", "-fsyntax-only", "-Xclang", "-ast-dump=json"]
    # core/ alone: every public header, no ns-3.
    tu = work / "core-tu.cc"
    tu.write_text("".join(f'#include "{h}"\n' for h in core_headers(repo)))
    for f, ns in top_level_namespaces(base + ["-I", str(repo / "core"), str(tu)], work, {"swarm"}):
        walk("core", "swarm", ns.get("inner", []), "", out, source(work, f))
    if include is None:
        return out
    # the module's headers, as a consumer includes them: ns3/<name>.h.
    staged = work / "inc" / "ns3"
    (staged / "testbench").mkdir(parents=True, exist_ok=True)
    for h in core_headers(repo):
        (staged / h).symlink_to(repo / "core" / h)
    ours = module_files(repo, "HEADER_FILES", ".h")
    for h in ours:
        (staged / Path(h).name).symlink_to(repo / h)
    tu = work / "ns3-tu.cc"
    tu.write_text("".join(f'#include "ns3/{Path(h).name}"\n' for h in ours))
    mine = {str((repo / h).resolve()) for h in ours}
    cmd = base + ["-I", str(work / "inc"), "-I", str(include), str(tu)]
    for f, ns in top_level_namespaces(cmd, work, {"ns3"}):
        if str((work / f).resolve()) in mine:
            walk("ns3", "ns3", ns.get("inner", []), "", out, source(work, f))
    return out


# --- TypeId registrations -------------------------------------------------------


def split_args(text: str) -> list[str]:
    """Top-level comma-separated arguments, respecting (), <>, {}, [] and strings."""
    args, depth, cur, i = [], 0, [], 0
    while i < len(text):
        c = text[i]
        if c == '"':
            j = i + 1
            while j < len(text) and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            cur.append(text[i : j + 1])
            i = j + 1
            continue
        if c in "(<{[":
            depth += 1
        elif c in ")>}]":
            depth -= 1
        if c == "," and depth == 0:
            args.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        args.append("".join(cur))
    return [" ".join(a.split()) for a in args]


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


WORD = re.compile(r"\w+")


def skip_space(text: str, i: int) -> int:
    while i < len(text) and text[i].isspace():
        i += 1
    return i


def matching(text: str, i: int, opening: str, closing: str) -> int:
    """The index of the bracket closing the one at I."""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == opening:
            depth += 1
        elif text[j] == closing:
            depth -= 1
            if depth == 0:
                return j
    raise SurfaceError(f"unbalanced {opening}{closing} at offset {i}")


def chain_calls(text: str, start: int) -> list[tuple[str, str, str]]:
    """The `.Name<targs>(args)` calls chained from START up to the closing `;`."""
    calls = []
    i = start
    while True:
        # `.Name`, optional `<targs>` (bracket-matched), then `(`; scanned by hand,
        # not by one regex, so a long chain costs linear time.
        i = skip_space(text, i)
        if i >= len(text) or text[i] != ".":
            break
        m = WORD.match(text, skip_space(text, i + 1))
        if not m:
            break
        name, i = m.group(0), skip_space(text, m.end())
        targs = ""
        if i < len(text) and text[i] == "<":
            close = matching(text, i, "<", ">")
            targs, i = text[i + 1 : close], skip_space(text, close + 1)
        if i >= len(text) or text[i] != "(":
            break
        depth, j = 1, i + 1
        open_at = j
        while depth and j < len(text):
            if text[j] == '"':
                j += 1
                while text[j] != '"':
                    j += 2 if text[j] == "\\" else 1
            elif text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
            j += 1
        calls.append((name, " ".join(targs.split()), text[open_at : j - 1]))
        i = j
    return calls


def unquote(s: str) -> str:
    return s[1:-1] if len(s) >= 2 and s[0] == s[-1] == '"' else s


def typeid_surface(repo: Path) -> set[str]:
    out: set[str] = set()
    files = module_files(repo, "SOURCE_FILES", ".cc") + module_files(repo, "HEADER_FILES", ".h")
    start = re.compile(r'\bTypeId\s*\(\s*"(ns3::[\w:]+)"\s*\)')
    for f in files:
        text = strip_comments((repo / f).read_text())
        for m in start.finditer(text):
            tid = m.group(1)
            line = {"parent": "-", "group": "-", "constructor": "no"}
            for name, targs, args in chain_calls(text, m.end()):
                a = split_args(args)
                if name == "SetParent":
                    line["parent"] = targs or (a[0] if a else "-")
                elif name == "SetGroupName":
                    line["group"] = unquote(a[0])
                elif name == "AddConstructor":
                    line["constructor"] = "yes"
                elif name == "AddAttribute":
                    flags = ""
                    if len(a) > 2 and a[2].startswith(("TypeId::ATTR_", "ATTR_")):
                        flags = f" flags={a[2]}"
                        a = a[:2] + a[3:]
                    out.add(
                        f"attribute {tid}::{unquote(a[0])}{flags} initial={a[2]} checker={a[4]}"
                    )
                    if len(a) > 5:  # a support level: its own line, so deprecating is not a change
                        out.add(f"attribute-support {tid}::{unquote(a[0])} {a[5]}")
                elif name == "AddTraceSource":
                    out.add(f"trace {tid}::{unquote(a[0])} callback={unquote(a[3])}")
                    if len(a) > 4:
                        out.add(f"trace-support {tid}::{unquote(a[0])} {a[4]}")
            out.add(
                f"typeid {tid} parent={line['parent']} group={line['group']} constructor={line['constructor']}"
            )
    return out


# --- the record and the check ---------------------------------------------------


IMAGE = re.compile(r"^[a-z0-9][a-z0-9._/:@-]*$")


def ns3_include_from_image(image: str, work: Path) -> Path:
    """Copy an ns3-dev image's ns-3 headers to WORK and point its stubs there.

    ns-3's build/include/ns3/*.h are one-line stubs that include the header in
    /opt/ns-3/src by its absolute path; they are rewritten to the copy."""
    if not IMAGE.match(image):
        raise SurfaceError(f"not an image reference: {image!r}")
    dest = (work / "ns3tree").resolve()
    dest.mkdir()
    find = 'cd / && find opt/ns-3/src opt/ns-3/contrib opt/ns-3/build/include -name "*.h" 2>/dev/null | tar cf - -T -'
    docker = subprocess.Popen(
        ["docker", "run", "--rm", image, "bash", "-c", find], stdout=subprocess.PIPE
    )
    subprocess.run(["tar", "xf", "-", "-C", str(dest)], stdin=docker.stdout, check=True)
    if docker.wait() != 0:
        raise SurfaceError(f"could not copy the ns-3 headers out of {image}")
    include = dest / "opt" / "ns-3" / "build" / "include"
    for stub in (include / "ns3").glob("*.h"):
        if stub.is_symlink() or not stub.resolve().is_relative_to(dest):
            continue  # only the copied stubs themselves are rewritten
        text = stub.read_text()
        if '"/opt/ns-3/' in text:
            stub.write_text(text.replace('"/opt/ns-3/', f'"{dest}/opt/ns-3/'))
    return include


def generate(repo: Path, include: Path | None, work: Path) -> str:
    lines = sorted(cxx_surface(repo, include, work) | typeid_surface(repo))
    return HEADER + "".join(line + "\n" for line in lines)


def items(text: str) -> list[str]:
    return [line for line in text.splitlines() if line and not line.startswith("#")]


def is_breaking(title: str, body: str) -> bool:
    return bool(BREAKING_TITLE.match(title.strip()) or BREAKING_FOOTER.search(body))


def findings(generated: str, committed: str, base: str | None, title: str, body: str) -> list[str]:
    found = []
    if generated != committed:
        diff = "".join(
            difflib.unified_diff(
                committed.splitlines(True),
                generated.splitlines(True),
                "committed",
                "generated",
                n=0,
            )
        )
        found.append(
            f"{SNAPSHOT} is stale: run `tools/checks/check-api-surface.py generate --ns3-image "
            f"ghcr.io/swarm-routing/ns3-dev:latest-debug` and commit it.\n{diff}"
        )
    if base is not None:
        gone = sorted(set(items(base)) - set(items(committed)))
        if gone and not is_breaking(title, body):
            found.append(
                f"{len(gone)} API item(s) removed or changed against the base, and the PR is not marked "
                "breaking (a `!` before the colon of its title, or a `BREAKING CHANGE:` footer in its body; "
                'docs/api-policy.md "Versions"):\n' + "\n".join(f"  - {g}" for g in gone)
            )
    return found


def report(found: list[str], strict: bool) -> int:
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    for f in found:
        first, _, rest = f.partition("\n")
        if strict:
            print(f"::error::{first}")
        else:
            print(f"::warning::{first} (report-only until the v1.0.0 freeze)")
        if rest:
            print(rest)
    if summary:
        with open(summary, "a") as fh:
            fh.write("## API surface\n\n")
            fh.write(
                "\n\n".join(f"```\n{f}\n```" for f in found)
                if found
                else "No removed or changed item; the record is current.\n"
            )
    if not found:
        print(
            "check-api-surface: ok (the record is current; nothing removed or changed against the base)"
        )
    return 1 if found and strict else 0


def main(argv: list[str]) -> int:
    if argv == ["--self-test"]:
        return self_test()
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("mode", choices=["generate", "check"])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--ns3-image")
    src.add_argument("--ns3-include", type=Path)
    ap.add_argument("-o", "--output", type=Path, default=REPO / SNAPSHOT)
    ap.add_argument("--base-snapshot", type=Path)
    ap.add_argument("--title", default="")
    ap.add_argument("--body-file", type=Path)
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--repo", type=Path, default=REPO)
    args = ap.parse_args(argv)
    try:
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp)
            include = (
                args.ns3_include.resolve()
                if args.ns3_include
                else ns3_include_from_image(args.ns3_image, work)
            )
            text = generate(args.repo.resolve(), include, work)
    except (SurfaceError, OSError, subprocess.CalledProcessError) as e:
        print(f"check-api-surface: {e}", file=sys.stderr)
        return 2
    if args.mode == "generate":
        args.output.write_text(text)
        print(f"check-api-surface: wrote {args.output} ({len(items(text))} items)")
        return 0
    committed = (args.repo / SNAPSHOT).read_text() if (args.repo / SNAPSHOT).exists() else ""
    base = (
        args.base_snapshot.read_text()
        if args.base_snapshot and args.base_snapshot.exists()
        else None
    )
    body = args.body_file.read_text() if args.body_file else ""
    return report(findings(text, committed, base, args.title, body), args.strict)


