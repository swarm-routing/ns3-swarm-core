def self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "repo"
        make_fake(root)
        work = Path(tmp) / "work"
        work.mkdir()
        text = generate(root, root / "ns3inc", work)
        got = set(items(text))
        expect = {
            "core enum class swarm::core::Kind : std::uint8_t",
            "core enumerator swarm::core::Kind::kA = 0",
            "core enumerator swarm::core::Kind::kB = 5",
            "core enumerator swarm::core::Kind::kC = 6",
            "core var swarm::core::kWireVersion (constexpr): const std::uint8_t = 3",
            "core alias swarm::core::NodeAddress = std::uint32_t",
            "core class swarm::core::Table",
            "core function swarm::core::Table::Table public explicit: void (int) [defaults 0=4 * 2]",
            "core function swarm::core::Table::~Table public virtual constexpr: void () = default",
            "core function swarm::core::Table::pick public virtual: int (double) const = 0",
            "core function swarm::core::Table::count public static: int ()",
            "core field swarm::core::Table::visible (public): int = 1",
            "core function swarm::core::Table::hook protected: void (NodeAddress, bool) [defaults 1=true]",
            "core template<typename T, int N = 2> struct swarm::core::Ring",
            "core field swarm::core::Ring::v (public): T[N]",
            "core template<typename T> function swarm::core::twice: T (T)",
            "core function swarm::core::free_fn: int (int, int) [defaults 1=kWireVersion]",
            "core struct swarm::core::testbench::Rng",
            "core function swarm::core::testbench::Rng::next public: std::uint64_t ()",
            "ns3 var ns3::kSwarmCoreApiVersion (constexpr): const uint32_t = 2",
            "ns3 class ns3::Monitor : public Object",
            "ns3 function ns3::Monitor::GetTypeId public static: TypeId ()",
            "ns3 function ns3::Monitor::Watch public: void (swarm::core::NodeAddress)",
            "ns3 function ns3::Monitor::OnChange protected virtual: void (bool)",
            "typeid ns3::Monitor parent=Object group=SwarmCore constructor=yes",
            "attribute ns3::Monitor::Alpha initial=DoubleValue(0.5) checker=MakeDoubleChecker<double>(0, 1)",
            "trace ns3::Monitor::Change callback=ns3::Monitor::ChangeCallback",
            "trace ns3::Monitor::Old callback=ns3::Monitor::ChangeCallback",
            "trace-support ns3::Monitor::Old TypeId::SupportLevel::DEPRECATED",
            "core function swarm::core::old_fn: int ()",
            "core deprecated swarm::core::old_fn",
        }
        missing, extra = expect - got, got - expect
        # the destructor's spelling of noexcept varies with clang; accept either form
        for line in list(missing):
            alt = line.replace(" noexcept", "")
            if alt in extra:
                missing.discard(line)
                extra.discard(alt)
        assert not missing and not extra, f"missing {sorted(missing)}\nextra {sorted(extra)}"
        assert not any("hidden_" in g or "secret" in g or "nope" in g or "m_x" in g for g in got)
        # determinism: the same sources give the same bytes
        work2 = Path(tmp) / "work2"
        work2.mkdir()
        assert generate(root, root / "ns3inc", work2) == text
        # the check
        assert findings(text, text, text, "feat: x", "") == []
        added = text + "core function swarm::core::new_fn: int ()\n"
        assert findings(added, added, text, "feat: add", "") == [], "an addition is not breaking"
        stale = findings(text, added, text, "feat: add", "")
        assert len(stale) == 1 and "stale" in stale[0]
        removed = HEADER + "".join(f"{x}\n" for x in sorted(got) if "free_fn" not in x)
        f = findings(removed, removed, text, "feat: drop free_fn", "")
        assert len(f) == 1 and "free_fn" in f[0] and "not marked breaking" in f[0]
        assert findings(removed, removed, text, "feat!: drop free_fn", "") == []
        assert findings(removed, removed, text, "refactor(core)!: drop", "") == []
        assert (
            findings(removed, removed, text, "feat: drop", "text\n\nBREAKING CHANGE: free_fn goes")
            == []
        )
        assert findings(removed, removed, None, "feat: drop", "") == [], (
            "no base record: nothing to compare"
        )
        with contextlib.redirect_stdout(io.StringIO()):
            assert report([], strict=True) == 0
            assert report(["x"], strict=False) == 0 and report(["x"], strict=True) == 1
        assert split_args('"a, b", F(1, 2), G<int, 3>()') == ['"a, b"', "F(1, 2)", "G<int, 3>()"]
    print("check-api-surface: self-test ok")
    return 0


